// Reads src/icons/icons.config.ts, copies the shape of each listed Material Symbol
// into src/icons/generated/paths.ts, and copies the Apache 2.0 licence next to it.
// Run it with `pnpm --filter @detriz-sh-kit/ui icons`.
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { iconConfig } from "../src/icons/icons.config.ts";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(packageRoot, "src/icons/generated");

// Where pnpm installed the Material Symbols SVGs.
const require = createRequire(import.meta.url);
const sourceDir = dirname(
  require.resolve("@material-symbols/svg-400/package.json"),
);

// Every Material Symbol is drawn in this coordinate box. The Icon component relies on it.
const VIEW_BOX = "0 -960 960 960";

const { style, icons } = iconConfig;
const errors = [];
const paths = {};

for (const name of icons) {
  if (name in paths) {
    errors.push(`"${name}" is listed twice.`);
    continue;
  }

  const file = join(sourceDir, style, `${name}.svg`);
  if (!existsSync(file)) {
    errors.push(
      `"${name}" doesn't exist in ${style}. Check the name at https://fonts.google.com/icons`,
    );
    continue;
  }

  const svg = readFileSync(file, "utf8");
  if (!svg.includes(`viewBox="${VIEW_BOX}"`)) {
    errors.push(
      `"${name}" has an unexpected viewBox. The Icon component expects "${VIEW_BOX}".`,
    );
    continue;
  }

  // Keep only the shape data (the `d` of each <path>). Several paths can be joined into one.
  paths[name] = [...svg.matchAll(/ d="([^"]+)"/g)]
    .map((match) => match[1])
    .join(" ");
}

if (errors.length > 0) {
  console.error(`Icons were not generated:\n- ${errors.join("\n- ")}`);
  process.exit(1);
}

// Sorted, so the generated file only changes where an icon was added or removed.
const entries = Object.keys(paths)
  .sort()
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths[name])},`);

const output = `// Generated by scripts/generate-icons.mjs from src/icons/icons.config.ts. Do not edit by hand.
// Shapes: Material Symbols (${style}, weight 400) by Google, Apache License 2.0. See ./LICENSE.

/** The shape (SVG path data) of every icon in the kit, by name. */
export const iconPaths = {
${entries.join("\n")}
} as const;

/** The name of an icon in the kit. A typo is a type error. */
export type IconName = keyof typeof iconPaths;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "paths.ts"), output);
copyFileSync(join(sourceDir, "LICENSE"), join(outDir, "LICENSE"));

console.log(
  `Generated ${entries.length} icons (${style}) in src/icons/generated/paths.ts`,
);
